#python program to demonstrate relational operators (print comparison results)
a = int(input("Enter a number: "))
b = int(input("Enter a number: "))
print("a > b:", a > b)
print("a < b:", a < b)
print("a == b:", a == b)
print("a != b:", a != b)
print("a >= b:", a >= b)
print("a <= b:", a <= b)